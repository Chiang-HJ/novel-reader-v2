def encode_polyline(points, factor):
    result = []
    prev_lat, prev_lng = 0, 0
    for lat, lng in points:
        lat_int = int(round(lat * factor))
        lng_int = int(round(lng * factor))
        d_lat = lat_int - prev_lat
        d_lng = lng_int - prev_lng
        prev_lat = lat_int
        prev_lng = lng_int
        for d in (d_lat, d_lng):
            d = (d << 1) ^ (d >> 31)
            while d >= 0x20:
                result.append(chr((0x20 | (d & 0x1f)) + 63))
                d >>= 5
            result.append(chr(d + 63))
    return ''.join(result)

